# -*- coding: utf-8 -*-
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx_helpers import set_cell_background, set_cell_margins, add_callout
from chapter1 import add_heading_1, add_heading_2

def build_chapter_5(doc):
    add_heading_1(doc, "第五章：防线固锁——“30秒闭环”防御性面试剧本与探私封堵")
    
    add_heading_2(doc, "1. 问题：面试室里的道德与心理审判")
    doc.add_paragraph(
        "在所有重返职场的关键关卡中，最令求职者感到心理崩溃的瞬间，莫过于在电话初筛或现场面试进行到中途时，"
        "面试官突然放下手中的简历，眼神复杂地抛出那个不可避免的问题："
        "“我注意到你 2022 年底离职后，中间有整整两年多没有正式全职工作记录，这段时间你到底在干什么？能具体讲讲吗？”"
    )
    doc.add_paragraph(
        "在这一刻，绝大多数曾经历过亲人重病去世、失能照料或大病手术的求职者，会瞬间遭遇强烈的创伤应激："
        "由于感到难堪、心虚或委屈，他们的语调开始颤抖，要么支支吾吾试图掩饰，要么不由自主地向面试官大倒苦水，"
        "详细倾诉那段暗无天日的陪护血泪史。而结果往往是灾难性的：面试官带着客套的同情点点头，面试结束后毫不留情地将其淘汰。"
    )

    add_heading_2(doc, "2. 为什么发生：雇主的核心恐惧是“复发与精力分散”")
    doc.add_paragraph(
        "求职者之所以在面试对话中屡屡败北，是因为他们严重误解了面试官提问背后的真实商业心理。\n"
        "求职者以为面试官在考察自己的“道德水平”或“生活经历”；\n"
        "但**商业机构不是慈善救助站，面试官提问的背后只有一个冷酷的考核点：【你的家庭危机是否已经彻底终结？你入职后会不会因为家庭琐事频繁请假旷工、情绪失控或再度辞职？】**"
    )
    doc.add_paragraph(
        "当你在面试中花费几分钟详细倾诉家庭的悲惨境遇时，你实际上在无意识中向雇主传递了极其危险的三重负面信号：\n"
        "1. 你的情绪依然深陷在过去的创伤与哀伤中，心理抗压能力堪忧；\n"
        "2. 你缺乏职业边界感，在严肃商业场合过度分享个人私生活；\n"
        "3. 你的家庭责任似乎非常沉重，极有可能在项目最紧急的关头因“家中有事”离岗。"
    )

    add_heading_2(doc, "3. 常见错误：诉苦陷阱与谎言漏洞")
    doc.add_paragraph("在回答空白期问题时，必须绝对避免以下三种致命错误：")
    doc.add_paragraph("• 【致命错误一：祥林嫂式情感倾泻（诉苦）】详述病房看护、医疗转院、药物副作用、亲人离世痛苦等细节。这会瞬间把专业商业对话拉低为居委会调解现场，让面试官感到尴尬和沉重，产生极强的防御心理。")
    doc.add_paragraph("• 【致命错误二：心虚道歉与自我贬低】使用“我那时候实在没办法”、“荒废了两年”、“可能跟不上现在的节奏”等消极词汇。在商业博弈中，求职者一旦主动自我贬低，面试官便顺理成章地将其作为压低薪资或直接淘汰的依据。")
    doc.add_paragraph("• 【致命错误三：虚构不成立的创业项目】宣称“我这两年一直在跟朋友合伙开公司创业做电商”。面试官稍微深究一句“获客成本多少、月流水多少、为什么突然不做了”，假话立刻被戳穿，直接被定义为诚信败坏。")

    add_heading_2(doc, "4. 正确方法：“30 秒闭环转折框架”（The 30-Second Pivot）")
    doc.add_paragraph(
        "破解这一困局的终极法则，是严格执行**【30 秒三段式闭环转折框架】**。\n"
        "该框架的全部目的，是在精确控制在 30 秒至 45 秒的时间内，按顺序完成三大心理动作：\n"
        "**【坦荡定性（10秒）】 → 【彻底切断顾虑（10秒）】 → 【强力拉回当下战力（10秒）】**，"
        "在展现高度伦理责任感的同时，以极高的情商与职业边界感封死面试官继续探私的空间，瞬间反客为主。"
    )

    add_callout(
        doc,
        "30秒闭环框架三大黄金法则：\n"
        "1. 事实坦荡陈述，绝不道歉；承担家庭重度照料责任是崇高且负责任的人格展现。\n"
        "2. 必须明确使用【彻底结束、圆满解决、完全解除约束（Permanently Resolved）】等不可逆词汇，焊死雇主关于‘复发请假’的全部担忧。\n"
        "3. 话音落下的最后一秒，必须抛出一个与目标公司具体业务痛点挂钩的技术反问，强行将话题拽回正轨。",
        title="防御性面试核心法则"
    )

    add_heading_2(doc, "5. 具体步骤：逐字拆解 30 秒黄金应答模块")
    doc.add_paragraph("请将以下三段式结构刻入肌肉记忆：")

    doc.add_paragraph("【第 1 阶段：坦荡定性（前 10 秒，给出事实边界，绝不展开）】\n"
                  "- 核心句式：“*那段时间，我主动安排了一段计划内的家庭事务休假（Career Break），全职负责处理一位直系长辈的突发医疗看护事宜……*”\n"
                  "- 心理学作用：光明磊落，定性为“主动安排的家庭责任”，展现出遇事不推卸、能够妥善处置家庭重任的成熟担当。")

    doc.add_paragraph("【第 2 阶段：彻底切断（中间 10 秒，消灭雇主所有风险假设）】\n"
                  "- 核心句式：“*……目前，这项家庭事务已经彻底、圆满地画上了句号（长辈已安详离世 / 长期医疗看护已完全由专业医疗托管机构妥善接管），我的个人精力已经 100% 彻底释放……*”\n"
                  "- 心理学作用：用确定性极强的终结词汇，从根本上拔除面试官对“后续是否还会请假、分心”的后顾之忧。")

    doc.add_paragraph("【第 3 阶段：强力拉回（最后 10 秒，无缝反弹至岗位战力）】\n"
                  "- 核心句式：“*……在过去几个月里，我通过独立顾问项目系统重构了对 [现代工具栈] 的应用，并一直保持着对行业的密切跟进。我今天之所以对贵司该岗位如此兴奋，正是因为我看到你们在 [某项具体业务] 上的挑战，而这恰好是我最擅长且拥有充足精力去解决的。*”\n"
                  "- 心理学作用：在对方还没来得及追问隐私之前，把聚光灯重新打回面试的核心——“我能为你解决什么业务问题”。")

    add_heading_2(doc, "6. 示例：针对三种真实生活情境的逐字稿演练")
    
    # 逐字稿表格
    table = doc.add_table(rows=4, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    
    headers = ["真实生活情境", "标准录音级 30 秒应答逐字稿（直接背诵应用）"]
    col_widths = [1.8, 4.4]
    
    for i, title in enumerate(headers):
        cell = table.cell(0, i)
        cell.width = Inches(col_widths[i])
        set_cell_background(cell, "EDF2F7")
        set_cell_margins(cell, 80, 80, 100, 100)
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(title)
        run.font.bold = True
        run.font.size = Pt(9.5)
        run.font.color.rgb = RGBColor(0x2D, 0x37, 0x48)
        
    script_data = [
        ("情境一：长辈失智 / 重病已安详离世", 
         "“2022年底我主动申请了一段职业休假，全职陪护家中患病长辈走完生命最后一程。这是一段非常沉重但身为子女必须全力以赴的家庭责任。目前这项事务已经完全、圆满地画上了句号，我的个人精力与时间已经100%彻底解除约束。在最近这半年里，我通过为两家小微企业提供独立业务顾问服务，系统更新了数字化协同流程。我今天非常看好贵司在华东区域的业务拓展，这正是我过去多年最核心的战力所在。”"),
        
        ("情境二：长辈慢性重病但目前已安排专业托管/恢复", 
         "“前两年因家中长辈突发严重的神经系统疾病，我全职协调并主持了整个阶段的紧急医疗排期与康复体系搭建。目前长辈的病情已进入极其稳定的慢性期，全家已全面交接由专业康复护理机构与全职专职护工照料，我的个人日常照护职责已彻底终结，具备完全不受干扰的随时到岗工作条件。近几个月我主导完成了某某咨询项目，保持着高度活跃的专业状态，迫不及待想要重返高节奏团队发挥价值。”"),
        
        ("情境三：个人大病手术康复归来", 
         "“在2023年期间，我主动暂停了工作，全力配合完成了一项计划内的重大外科医疗干预与系统性术后康复。目前经过三家三甲医院的全面医学复查，我的身体指标已完全恢复至最佳健康水平，并获得了主治医师出具的全职高强度工作许可。这场经历让我具备了比以往更强韧的身心状态。最近我系统复盘了行业前沿工具链，我非常有信心将我成熟的风险把控经验注入到贵司当下的核心项目中。”")
    ]
    
    for row_idx, data in enumerate(script_data, start=1):
        for col_idx, text in enumerate(data):
            cell = table.cell(row_idx, col_idx)
            cell.width = Inches(col_widths[col_idx])
            set_cell_margins(cell, 80, 80, 100, 100)
            if row_idx % 2 == 1:
                set_cell_background(cell, "FFFFFF")
            else:
                set_cell_background(cell, "F7FAFC")
            p = cell.paragraphs[0]
            run = p.add_run(text)
            run.font.size = Pt(9)
            if col_idx == 0:
                run.font.bold = True
                run.font.color.rgb = RGBColor(0x1A, 0x36, 0x5D)
            else:
                run.font.color.rgb = RGBColor(0x2D, 0x37, 0x48)

    doc.add_paragraph().paragraph_format.space_after = Pt(4)

    add_heading_2(doc, "7. 检查清单：面试语言雷区 7 严禁")
    doc.add_paragraph("在进入任何面试考场之前，在心中默念以下 7 条红线禁令：")
    doc.add_paragraph("【1】严禁出现抽泣、眼眶泛红或情绪哽咽等非职业性生理失控。")
    doc.add_paragraph("【2】严禁展开医疗、病理、化疗、手术或看护的任何生化技术细节。")
    doc.add_paragraph("【3】严禁使用“命运不公、倒霉、被逼无奈、走投无路”等受害者怨妇口吻。")
    doc.add_paragraph("【4】严禁提及“家庭开销巨大急需这份工资糊口”（暴露出脆弱议价心态）。")
    doc.add_paragraph("【5】严禁模棱两可地说“现在稍微好点了、有空来上班了”（引发复发联想）。")
    doc.add_paragraph("【6】严禁抱怨过往医院制度或前雇主缺乏同情心。")
    doc.add_paragraph("【7】严禁回答时间超过 45 秒（时间一长必定开始过度暴露私生活细节）。")

    add_heading_2(doc, "8. 读者可以立即执行的行动")
    doc.add_paragraph(
        "【立即行动】：拿出手机打开录音机，把第 6 节中与你最接近的那段逐字稿大声朗读一遍，记录耗时。"
        "接着合上文档，仅凭记忆中的三大支柱（定性 → 切断 → 拉回）用你自己的口语重述一遍并录音。"
        "反复回听录音，直到语速平缓从容、中气十足，严格控制在 30 秒至 40 秒内收尾。这就是你未来在任何面试间立于不败之地的定海神针。"
    )
    
    doc.add_page_break()

print("Chapter 5 module ready.")
